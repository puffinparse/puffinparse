//! Finds the run viewer's front-end for `puffinparse eval view`.
//!
//! The local viewer is the benchmark site's own viewer (ADR-28: one UI on puffinparse.com and on
//! the user's machine), so its sources live in `benchmark/site/src/` and `website/assets/`. A
//! crate packaged for crates.io cannot reach outside its own folder; the release job runs
//! `scripts/vendor_viewer.py` first, which copies the same files into `viewer/` here. The repo
//! copy wins whenever both exist.

use std::path::{Path, PathBuf};

const ASSETS: &[(&str, &str, &str)] = &[
    ("INDEX_HTML", "benchmark/site/src/index.html", "index.html"),
    ("APP_JS", "benchmark/site/src/app.js", "app.js"),
    ("STYLES_CSS", "benchmark/site/src/styles.css", "styles.css"),
    ("TOKENS_CSS", "website/assets/tokens.css", "tokens.css"),
];

fn main() {
    let crate_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let repo = crate_dir.join("../..");
    let mut out = String::from("// Generated by build.rs: the viewer's front-end files.\n");
    for (name, in_repo, vendored) in ASSETS {
        let path = locate(&repo.join(in_repo), &crate_dir.join("viewer").join(vendored)).unwrap_or_else(|| {
            panic!("viewer asset {in_repo} not found; outside the repository run scripts/vendor_viewer.py first")
        });
        println!("cargo:rerun-if-changed={}", path.display());
        out += &format!("pub const {name}: &str = include_str!({:?});\n", path.display().to_string());
    }
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("viewer_assets.rs");
    std::fs::write(dest, out).expect("write viewer_assets.rs");
}

fn locate(in_repo: &Path, vendored: &Path) -> Option<PathBuf> {
    [in_repo, vendored].into_iter().find(|p| p.is_file()).and_then(|p| p.canonicalize().ok())
}
